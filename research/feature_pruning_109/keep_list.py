"""Write ``src/store_columns.py``: the numeric feature columns the store keeps (research 109).

    python -m research.feature_pruning_109.keep_list

A numeric feature column is kept when anything names it:
- any registered feature-set file (``feature_sets/*.txt``), live or retired;
- the inputs of every saved run that can be loaded (``src.run_store.list_runs``);
- the forecast correction's tracking, entity, card and settled columns;
- every raw rating column, which ``src.rating_reuse`` reads back from the store to skip the rating sweep;
- any string literal equal to a store column in code that reads the finished store (``src/`` outside the
  feature-producing modules, ``scripts/``).
Non-numeric columns and ``src.model.EXCLUDE_COLUMNS`` (keys, labels, metadata) are never pruned.
"""
import ast
import glob
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

from src.correction import data as cd
from src.correction import inputs as ci
from src.feature_store import FeatureStore
from src.model import EXCLUDE_COLUMNS

TARGET = Path("src/store_columns.py")


def numeric_features(schema):
    return {f.name for f in schema if f.name not in EXCLUDE_COLUMNS and
            (pa.types.is_integer(f.type) or pa.types.is_floating(f.type) or pa.types.is_boolean(f.type))}


def feature_set_names():
    names = set()
    for path in glob.glob("feature_sets/*.txt"):
        for line in Path(path).read_text(encoding="utf-8-sig").splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                names.add(line)
    return names


def run_features():
    from src.run_store import list_runs, load_run_predictor
    names, loaded = set(), 0
    for run in list_runs():
        try:
            predictor = load_run_predictor(run["run_id"])
        except Exception:
            continue
        if predictor is None:
            continue
        loaded += 1
        for member in (getattr(predictor, "models", None) or {}).values():
            spec = getattr(member, "spec", None)
            names.update(getattr(spec, "features", ()) or ())
        for attribute in ("feature_cols", "feature_names", "features"):
            names.update(getattr(predictor, attribute, None) or ())
    return names, loaded


#: Feature-producing modules name the columns they create; pruning runs after them, so only code that reads the
#: finished store counts. The store modules themselves read it back and stay in the scan.
STORE_READERS = {"src/feature_store.py", "src/featured_dataset.py", "src/store_build.py"}
RETIRED = {"src/bha_features.py", "src/bha_events.py", "src/store_columns.py"}


def rating_columns():
    import tempfile
    from src.data_processor import process_data
    from tests.test_live_parity import _synthetic_raw
    processed = process_data(_synthetic_raw(n_days=5, field=4))
    _, columns, _ = FeatureStore(tempfile.mkdtemp())._seeded_rating_frame(processed, None)
    return set(columns)


def code_literals(columns):
    from src.featured_dataset import _FE_SOURCE_FILES
    producers = {p.replace("\\", "/") for p in _FE_SOURCE_FILES} - STORE_READERS
    found = set()
    files = [*glob.glob("src/**/*.py", recursive=True), *glob.glob("scripts/*.py")]
    for path in files:
        if path.replace("\\", "/") in producers | RETIRED:
            continue
        try:
            tree = ast.parse(Path(path).read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value in columns:
                found.add(node.value)
    return found


def main():
    schema = pq.read_schema(FeatureStore().featured_path)
    ratings = rating_columns()
    features = numeric_features(schema) | ratings   # the store may already be pruned
    runs, loaded = run_features()
    correction = {*cd.tracking_columns(), *ci.ENTITY_COLUMNS, *cd.CARD_COLUMNS, *cd.SETTLED_COLUMNS}
    sources = {"feature sets": feature_set_names(), "saved runs": runs, "correction": correction, "ratings": ratings,
               "code literals": code_literals(features)}
    keep = set().union(*sources.values()) & features
    for label, names in sources.items():
        print(f"{label:14s} {len(names & features):4d} store features")
    print(f"keep {len(keep)} of {len(features)} numeric features ({loaded} runs loaded); "
          f"prune {len(features - keep)}")
    lines = ['"""Numeric feature columns the feature store keeps; every other numeric feature is dropped at the end of',
             "``engineer_features``. Generated by ``research/feature_pruning_109/keep_list.py`` from the feature-set files,",
             "saved runs, the forecast correction and column names in pipeline code (2026-11-15). To bring a dropped",
             'feature back, add it to a feature-set file and regenerate, or add it here by hand."""',
             "", "from contextlib import contextmanager", "", "KEEP = frozenset({"]
    lines += [f"    {name!r}," for name in sorted(keep)]
    lines += ["})", "", "_DISABLED = []", "", "",
              "@contextmanager",
              "def unpruned():",
              '    """Keep every column inside this block: tests of the feature code check columns the store drops."""',
              "    _DISABLED.append(True)",
              "    try:",
              "        yield",
              "    finally:",
              "        _DISABLED.pop()",
              "", "",
              "def prune(df):",
              '    """Drop numeric feature columns outside ``KEEP``; keys, labels, metadata and text are untouched."""',
              "    if _DISABLED:",
              "        return df",
              "    from src.model import EXCLUDE_COLUMNS",
              "    excluded = set(EXCLUDE_COLUMNS)",
              "    drop = [c for c in df.columns if c not in KEEP and c not in excluded and not c.startswith('_')",
              "            and (df[c].dtype.kind in 'biuf')]",
              "    return df.drop(columns=drop) if drop else df",
              ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
